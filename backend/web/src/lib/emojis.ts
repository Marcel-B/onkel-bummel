/** Splits the tags into the emojis in front of the title and the rest, which show as tags. */
export function splitTags(tags: string[]): { emojis: string; rest: string[] } {
  let prefix = ''
  const rest: string[] = []
  for (const tag of tags) {
    const emoji = emojis[tag.toLowerCase()]
    if (emoji) prefix += emoji
    else rest.push(tag)
  }
  return { emojis: prefix, rest }
}
